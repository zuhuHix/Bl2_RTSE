"""Generate rtse/item_assets.py (compact BL2 asset library tables) from Gibbed's dump.

Download the dump into its own empty directory, then run from the repo root:

    curl -sSL -o <dl>/alm.json "https://raw.githubusercontent.com/gibbed/Borderlands2Dumps/08c9a885e5939cc62ca82e9277e2f95580bf7850/Asset%20Library%20Manager.json"
    python -I dev/gen_item_assets.py <dl>/alm.json rtse/item_assets.py

Only integers are kept: per asset group the (sublibrary_bits, asset_bits) and, per set and
group, the number of assets in each sublibrary (in sublibrary order). No asset names.
"""

from __future__ import annotations

import hashlib
import json
import sys

DUMPS_COMMIT = "08c9a885e5939cc62ca82e9277e2f95580bf7850"
DUMPS_URL = (
    "https://github.com/gibbed/Borderlands2Dumps/blob/"
    f"{DUMPS_COMMIT}/Asset%20Library%20Manager.json"
)
GIBBED_COMMIT = "e7afdaf45265024725d55d9d19dfee5ce077ff2b"
GROUPS = ("WeaponTypes", "WeaponParts", "ItemTypes", "ItemParts", "Manufacturers", "BalanceDefs")


def _wrap(prefix: str, values: tuple, width: int = 100) -> list[str]:
    lines, cur = [], prefix + "("
    for v in values:
        piece = f"{v}, "
        if len(cur) + len(piece) > width:
            lines.append(cur.rstrip())
            cur = " " * (len(prefix) + 1)
        cur += piece
    lines.append(cur.rstrip().rstrip(",") + ("," if len(values) == 1 else "") + "),")
    return lines


def generate(raw: bytes) -> str:
    data = json.loads(raw.decode("utf-8-sig"))
    configs = data["configs"]
    out = [
        '"""Compact Borderlands 2 asset library tables for offline serial validation. GENERATED, do not edit.',
        "",
        f"Source: {DUMPS_URL}",
        f"  (Borderlands2Dumps commit {DUMPS_COMMIT}, the Dumps submodule pinned by",
        f"  Gibbed.Borderlands2 master {GIBBED_COMMIT}; file sha256 {hashlib.sha256(raw).hexdigest()})",
        "Generated by: python -I dev/gen_item_assets.py <downloaded alm.json> rtse/item_assets.py",
        "",
        "CONFIGS[group] = (sublibrary_bits, asset_bits). SETS[set_id][group] = asset count of each",
        "sublibrary, in sublibrary-index order. PC layout (Gibbed's Platform Configurations.json only",
        "remaps sublibraries for X360 set 9).",
        '"""',
        "",
        f"VERSION = {int(data['version'])}",
        "",
        "CONFIGS = {",
    ]
    for g in GROUPS:
        c = configs[g]
        out.append(f'    "{g}": ({int(c["sublibrary_bits"])}, {int(c["asset_bits"])}),')
    out += ["}", "", "SETS = {"]
    for s in sorted(data["sets"], key=lambda s: s["id"]):
        out.append(f"    {int(s['id'])}: {{")
        for g in GROUPS:
            subs = s["libraries"].get(g, {"sublibraries": []})["sublibraries"]
            counts = tuple(len(sl.get("assets") or ()) for sl in subs)  # Raw default: empty list
            if not counts:
                out.append(f'        "{g}": (),')
            else:
                out += _wrap(f'        "{g}": ', counts)
        out.append("    },")
    out += ["}", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    with open(argv[1], "rb") as f:
        text = generate(f.read())
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
